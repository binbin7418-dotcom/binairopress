#!/usr/bin/env python3
"""BinairoPress engine: Binairo (binary Sudoku) puzzle books (PDF)
where every puzzle is PROVEN to have exactly one solution.

Binairo rules on an NxN grid (N even): fill every cell with a filled
or an open circle so that (1) every row and column holds exactly N/2
of each kind, (2) never three of a kind in a row -- horizontally or
vertically, and (3) no two rows are identical and no two columns are
identical.

How a puzzle is made: a completed grid is generated by row-pattern
backtracking, then givens are dug in rotationally symmetric pairs;
a dig is only kept if a propagation solver proves the puzzle still
has exactly one solution. Deterministic for a fixed seed. 100%
local. Requires: reportlab.

Usage:
    python binairo_press.py out/ [--puzzles 12] [--size 8] [--seed 42]
"""
import os
import random
import sys

PAGE_W, PAGE_H = 612, 792

# ------------------------------------------------------------- solver

def _line_forced(line, n):
    """Given a partial line (list of -1 unknown, 0, 1), return a dict of
    forced {index: value} by the counting and no-three rules."""
    forced = {}
    half = n // 2
    for v in (0, 1):
        if sum(1 for x in line if x == v) == half:
            for i, x in enumerate(line):
                if x == -1:
                    forced[i] = 1 - v
    for i in range(n - 1):
        if line[i] != -1 and line[i] == line[i + 1]:
            v = 1 - line[i]
            if i - 1 >= 0 and line[i - 1] == -1:
                forced[i - 1] = v
            if i + 2 < n and line[i + 2] == -1:
                forced[i + 2] = v
    for i in range(n - 2):
        if line[i] != -1 and line[i] == line[i + 2] and line[i + 1] == -1:
            forced[i + 1] = 1 - line[i]
    return forced


def _line_ok(line, n):
    half = n // 2
    for v in (0, 1):
        if sum(1 for x in line if x == v) > half:
            return False
    for i in range(n - 2):
        if line[i] != -1 and line[i] == line[i + 1] == line[i + 2]:
            return False
    return True


def _complete_ok(grid, n):
    rows = [tuple(r) for r in grid]
    if len(set(rows)) != n:
        return False
    cols = [tuple(grid[r][c] for r in range(n)) for c in range(n)]
    if len(set(cols)) != n:
        return False
    return all(_line_ok(list(r), n) for r in rows) and \
        all(_line_ok(list(c), n) for c in cols)


def _propagate(grid, n):
    grid = [row[:] for row in grid]
    changed = True
    while changed:
        changed = False
        for r in range(n):
            if not _line_ok(grid[r], n):
                return None
            for i, v in _line_forced(grid[r], n).items():
                if grid[r][i] == -1:
                    grid[r][i] = v
                    changed = True
        for c in range(n):
            col = [grid[r][c] for r in range(n)]
            if not _line_ok(col, n):
                return None
            for i, v in _line_forced(col, n).items():
                if grid[i][c] == -1:
                    grid[i][c] = v
                    changed = True
        # uniqueness: a complete line forces any line matching it in all
        # known cells to differ somewhere -> handled by search; skip here
    return grid


def _solve_rec(grid, n, sols, limit):
    if len(sols) >= limit:
        return
    grid = _propagate(grid, n)
    if grid is None:
        return
    target = None
    for r in range(n):
        for c in range(n):
            if grid[r][c] == -1:
                target = (r, c)
                break
        if target:
            break
    if target is None:
        if _complete_ok(grid, n):
            sols.append(grid)
        return
    r, c = target
    for v in (0, 1):
        g2 = [row[:] for row in grid]
        g2[r][c] = v
        _solve_rec(g2, n, sols, limit)
        if len(sols) >= limit:
            return


def solve_binairo(givens, n, limit=2):
    sols = []
    _solve_rec([row[:] for row in givens], n, sols, limit)
    return sols

# ------------------------------------------------------------- construction

def _row_patterns(n):
    pats = []
    half = n // 2

    def rec(cur):
        if len(cur) == n:
            if sum(cur) == half:
                pats.append(tuple(cur))
            return
        for v in (0, 1):
            if len(cur) >= 2 and cur[-1] == v and cur[-2] == v:
                continue
            if sum(cur) + v > half:
                continue
            cur.append(v)
            rec(cur)
            cur.pop()

    rec([])
    return pats


def gen_solution(rng, n):
    pats = _row_patterns(n)
    grid = []

    def bt(r):
        if r == n:
            cols = [[grid[rr][c] for rr in range(n)] for c in range(n)]
            return all(_line_ok(col, n) and sum(col) == n // 2
                       for col in cols) and \
                len({tuple(col) for col in cols}) == n
        cand = pats[:]
        rng.shuffle(cand)
        for p in cand:
            if p in grid:
                continue
            ok = True
            for c in range(n):
                col = [grid[rr][c] for rr in range(r)] + [p[c]]
                if sum(col) > n // 2 or (len(col) >= 3 and
                                         col[-1] == col[-2] == col[-3]):
                    ok = False
                    break
            if not ok:
                continue
            grid.append(p)
            if bt(r + 1):
                return True
            grid.pop()
        return False

    if not bt(0):
        raise RuntimeError("no binairo solution")
    return [list(r) for r in grid]


def dig_givens(rng, solution, n):
    givens = [row[:] for row in solution]
    cells = [(r, c) for r in range(n) for c in range(n)]
    rng.shuffle(cells)
    seen = set()
    for (r, c) in cells:
        if (r, c) in seen:
            continue
        pair = [(r, c), (n - 1 - r, n - 1 - c)]
        seen.update(pair)
        saved = [(p, givens[p[0]][p[1]]) for p in pair]
        for (pr, pc) in pair:
            givens[pr][pc] = -1
        if len(solve_binairo(givens, n, limit=2)) != 1:
            for (pr, pc), v in saved:
                givens[pr][pc] = v
    return givens


def make_puzzle(rng, n):
    solution = gen_solution(rng, n)
    givens = dig_givens(rng, solution, n)
    sols = solve_binairo(givens, n, limit=2)
    assert len(sols) == 1 and sols[0] == solution
    return {"n": n, "givens": givens, "solution": solution,
            "given_count": sum(1 for r in range(n) for c in range(n)
                               if givens[r][c] != -1)}

# -------------------------------------------------------------------- PDF

def _draw_grid(c, p, ox, oy, cell, show_solution):
    from reportlab.lib.colors import HexColor
    n = p["n"]
    src = p["solution"] if show_solution else p["givens"]
    for r in range(n):
        for cc in range(n):
            x = ox + cc * cell
            y = oy + (n - 1 - r) * cell
            c.setFillColor(HexColor("#ffffff"))
            c.setStrokeColor(HexColor("#888888"))
            c.setLineWidth(0.8)
            c.rect(x, y, cell, cell, stroke=1, fill=1)
            v = src[r][cc]
            if v == 1:
                c.setFillColor(HexColor("#1a1a1a"))
                c.circle(x + cell / 2, y + cell / 2, cell * 0.30, stroke=0, fill=1)
            elif v == 0:
                c.setStrokeColor(HexColor("#1a1a1a"))
                c.setLineWidth(1.6)
                c.circle(x + cell / 2, y + cell / 2, cell * 0.30, stroke=1, fill=0)
    c.setStrokeColor(HexColor("#1a1a1a"))
    c.setLineWidth(2.2)
    c.rect(ox, oy, n * cell, n * cell, stroke=1, fill=0)


def render_pdf(path, puzzles):
    from reportlab.pdfgen import canvas as rl_canvas
    from reportlab.lib.colors import HexColor
    ink = HexColor("#1a1a1a")
    c = rl_canvas.Canvas(path, pagesize=(PAGE_W, PAGE_H))
    c.setFillColor(ink)
    c.setFont("Helvetica-Bold", 30)
    c.drawString(72, 640, "BinairoPress")
    c.setFont("Helvetica", 15)
    c.drawString(72, 606, "Half filled, half open. Never three in a row.")
    c.setFont("Helvetica", 11.5)
    lines = [
        "Fill every cell with a filled or an open circle. Each row and",
        "column holds exactly half of each kind, never three of a kind",
        "in a row (across or down), and no two rows or columns may end",
        "up identical.",
        "",
        "Every puzzle in this book was re-solved by a counting program",
        "before it was printed: each one has exactly one solution, and",
        "the full solutions are at the back.",
    ]
    y = 540
    for ln in lines:
        c.drawString(72, y, ln)
        y -= 20
    c.showPage()
    for i, p in enumerate(puzzles, 1):
        n = p["n"]
        cell = min(56.0, 470.0 / n)
        ox = (PAGE_W - n * cell) / 2
        oy = (PAGE_H - n * cell) / 2 - 10
        c.setFillColor(ink)
        c.setFont("Helvetica-Bold", 15)
        c.drawString(54, 748, f"Binairo {i} -- {n}x{n}, {p['given_count']} givens")
        _draw_grid(c, p, ox, oy, cell, False)
        c.showPage()
    c.setFont("Helvetica-Bold", 16)
    c.drawString(54, 748, "Solutions")
    c.showPage()
    per = 2
    for k in range(0, len(puzzles), per):
        for j, p in enumerate(puzzles[k:k + per]):
            n = p["n"]
            cell = min(34.0, 280.0 / n)
            ox = 60 + j * 290
            oy = 430
            c.setFillColor(ink)
            c.setFont("Helvetica-Bold", 12)
            c.drawString(ox, oy + n * cell + 12, f"Solution {k + j + 1}")
            _draw_grid(c, p, ox, oy, cell, True)
        c.showPage()
    c.save()
    with open(path, "rb") as fh:
        data = fh.read()
    return data.count(b"/Type /Page") - data.count(b"/Type /Pages")

# -------------------------------------------------------------------- run

def run_binairopress(count, outdir, seed=42, size=8, **kw):
    if size not in (6, 8, 10):
        raise ValueError("grid size must be 6, 8 or 10")
    os.makedirs(outdir, exist_ok=True)
    rng = random.Random(seed)
    puzzles = [make_puzzle(rng, size) for _ in range(count)]
    pdf_path = os.path.join(outdir, "binairo_book.pdf")
    pages = render_pdf(pdf_path, puzzles)
    return {"puzzles": puzzles, "pages": pages, "pdf_path": pdf_path,
            "count": len(puzzles)}


def main(argv):
    outdir = argv[1] if len(argv) > 1 else "out"
    opts = {"puzzles": 12, "size": 8, "seed": 42}
    for a in argv[2:]:
        if a.startswith("--") and "=" in a:
            k, v = a[2:].split("=", 1)
            opts[k] = int(v)
    s = run_binairopress(opts["puzzles"], outdir, seed=opts["seed"],
                         size=opts["size"])
    for i, p in enumerate(s["puzzles"], 1):
        print(f"Binairo {i}: {p['n']}x{p['n']}, {p['given_count']} givens, unique OK")
    print(f"Pages: {s['pages']}")
    print(f"PDF: {s['pdf_path']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
